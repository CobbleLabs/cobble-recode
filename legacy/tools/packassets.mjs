/*
 * packassets - concatenates every runtime asset into one blob that the payload
 * embeds as a single RCDATA resource, plus a header of typed spans into it.
 *
 *   node tools/packassets.mjs
 *
 * One resource beats hundreds of kilobytes of generated char arrays: MSVC never
 * has to parse the data, and the blob stays byte-identical to the source files.
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, basename, extname } from 'node:path';

const FONT_DIR = 'assets/fonts';
const ICON_DIR = 'assets/icons';
const BLOB_OUT = 'build/assets/cobble.assets';
const HEADER_OUT = 'payload/src/assets/Assets.generated.hpp';
const SOURCE_OUT = 'payload/src/assets/Assets.generated.cpp';

const FONTS = [
  ['InterRegular', 'Inter-Regular.ttf'],
  ['InterMedium', 'Inter-Medium.ttf'],
  ['InterSemiBold', 'Inter-SemiBold.ttf'],
  ['InterBold', 'Inter-Bold.ttf'],
  ['MonoMedium', 'JetBrainsMono-Medium.ttf'],
  ['MonoBold', 'JetBrainsMono-Bold.ttf'],
];

function pascal(name) {
  return name
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

const chunks = [];
let cursor = 0;

function append(bytes) {
  const span = { offset: cursor, size: bytes.length };
  chunks.push(bytes);
  cursor += bytes.length;
  // Keep every asset 4-byte aligned; stb_truetype is happier with aligned data.
  const padding = (4 - (cursor % 4)) % 4;
  if (padding > 0) {
    chunks.push(Buffer.alloc(padding));
    cursor += padding;
  }
  return span;
}

const fontEntries = FONTS.map(([id, file]) => ({
  id,
  file,
  span: append(readFileSync(join(FONT_DIR, file))),
}));

const iconFiles = readdirSync(ICON_DIR)
  .filter((name) => extname(name) === '.svg')
  .sort();

const iconEntries = iconFiles.map((file) => {
  const name = basename(file, '.svg');
  return {
    id: pascal(name),
    name,
    span: append(readFileSync(join(ICON_DIR, file))),
  };
});

const blob = Buffer.concat(chunks);
mkdirSync('build/assets', { recursive: true });
mkdirSync('payload/src/assets', { recursive: true });
writeFileSync(BLOB_OUT, blob);

const header = `// Generated by tools/packassets.mjs. Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>

namespace cold::assets {

struct Span {
    std::uint32_t offset;
    std::uint32_t size;
};

enum class FontAsset : std::uint8_t {
${fontEntries.map((entry) => `    ${entry.id},`).join('\n')}
    Count
};

enum class IconAsset : std::uint8_t {
${iconEntries.map((entry) => `    ${entry.id},`).join('\n')}
    Count
};

inline constexpr auto kFontCount = static_cast<std::size_t>(FontAsset::Count);
inline constexpr auto kIconCount = static_cast<std::size_t>(IconAsset::Count);
inline constexpr std::uint32_t kBlobSize = ${blob.length}u;

extern const Span kFontSpans[kFontCount];
extern const Span kIconSpans[kIconCount];
extern const char* const kIconNames[kIconCount];

}  // namespace cold::assets
`;

const source = `// Generated by tools/packassets.mjs. Do not edit.
#include "Assets.generated.hpp"

namespace cold::assets {

const Span kFontSpans[kFontCount] = {
${fontEntries.map((e) => `    {${e.span.offset}u, ${e.span.size}u},  // ${e.file}`).join('\n')}
};

const Span kIconSpans[kIconCount] = {
${iconEntries.map((e) => `    {${e.span.offset}u, ${e.span.size}u},  // ${e.name}.svg`).join('\n')}
};

const char* const kIconNames[kIconCount] = {
${iconEntries.map((e) => `    "${e.name}",`).join('\n')}
};

}  // namespace cold::assets
`;

writeFileSync(HEADER_OUT, header);
writeFileSync(SOURCE_OUT, source);

console.log(`blob ${(blob.length / 1024).toFixed(1)} KiB  fonts ${fontEntries.length}  icons ${iconEntries.length}`);
