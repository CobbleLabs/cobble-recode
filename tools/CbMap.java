    /** What structure and votes leave open: scored candidates, mutual best by a margin. */
    static final class Similarity {
        private static final double CLASS_MIN = 0.6;
        private static final double METHOD_MIN = 0.6;
        private static final double FIELD_MIN = 0.5;
        private static final double MARGIN = 0.1;
        /* Resolved tokens differ only where the bodies really do, so a copy CheatBreaker reworked still loses to the plain one. */
        private static final double RESOLVED_MARGIN = 0.02;

        private final Links links;

        Similarity(Links links) {
            this.links = links;
        }

        void matchClasses() {
            List<Cls> left = links.vanilla.values().stream().filter(c -> c.match == null).toList();
            List<Cls> right = links.cb.values().stream().filter(c -> c.match == null).toList();
            Map<Cls, Map<Cls, Double>> scores = new LinkedHashMap<>();
            for (Cls v : left) {
                for (Cls c : right) {
                    if (v.isInterface() == c.isInterface() && v.isEnum() == c.isEnum() && sameExternalSuper(v, c)) {
                        scores.computeIfAbsent(v, k -> new LinkedHashMap<>()).put(c, classScore(v, c));
                    }
                }
            }
            mutualBest(scores, CLASS_MIN, MARGIN).forEach(links::link);
        }

        private static boolean sameExternalSuper(Cls v, Cls c) {
            return (v.superCls == null) == (c.superCls == null)
                    && (v.superCls != null || v.node.superName.equals(c.node.superName));
        }

        private double classScore(Cls v, Cls c) {
            List<String> mv = new ArrayList<>();
            List<String> mc = new ArrayList<>();
            for (Fld f : v.fields.values()) {
                mv.add("F" + f.isStatic() + links.mapDesc(f.node.desc, true));
            }
            for (Fld f : c.fields.values()) {
                mc.add("F" + f.isStatic() + links.mapDesc(f.node.desc, false));
            }
            for (Mth m : v.methods.values()) {
                mv.add("M" + m.isStatic() + links.mapDesc(m.node.desc, true));
            }
            for (Mth m : c.methods.values()) {
                mc.add("M" + m.isStatic() + links.mapDesc(m.node.desc, false));
            }
            double structure = containment(mv, mc);
            double hierarchy = v.superCls != null && v.superCls.match != null ? (v.superCls.match == c.superCls ? 1 : 0)
                    : 0.5;
            double strings = !v.strings.isEmpty() || !c.strings.isEmpty() ? jaccard(v.strings, c.strings) : structure;
            double externals = v.externals.isEmpty() && c.externals.isEmpty() ? structure
                    : jaccard(v.externals, c.externals);
            return 0.35 * structure + 0.25 * strings + 0.2 * externals + 0.2 * hierarchy;
        }

        /** Scores bodies on their tokens, or with the members they reference resolved through the matches so far. */
        void matchMethods(boolean resolved) {
            for (Cls v : links.vanilla.values()) {
                Cls c = v.match;
                if (c == null) {
                    continue;
                }
                Map<Mth, List<String>> tokens = new HashMap<>();
                Function<Mth, List<String>> tokensOf = m -> !resolved ? m.tokens
                        : tokens.computeIfAbsent(m, k -> links.resolvedTokens(k, k.owner == v));
                Map<Mth, Map<Mth, Double>> scores = new LinkedHashMap<>();
                for (Mth mv : v.methods.values()) {
                    if (mv.match != null) {
                        continue;
                    }
                    for (Mth mc : c.methods.values()) {
                        if (mc.match != null || mv.isStatic() != mc.isStatic()
                                || !links.compatibleMethodDesc(mv.node.desc, mc.node.desc)
                                || isReal(mv.node.name) != isReal(mc.node.name)) {
                            continue;
                        }
                        int total = mv.tokens.size() + mc.tokens.size();
                        double score = total == 0 ? 1
                                : 2.0 * Voting.align(tokensOf.apply(mv), tokensOf.apply(mc)).length / total;
                        scores.computeIfAbsent(mv, k -> new LinkedHashMap<>()).put(mc, score);
                    }
                }
                mutualBest(scores, METHOD_MIN, resolved ? RESOLVED_MARGIN : MARGIN).forEach(links::link);
            }
        }

        /** The fields left are compared by which matched methods read and write them. */
        void matchFields() {
            Map<Fld, Set<String>> usageV = usage(links.vanilla, true);
            Map<Fld, Set<String>> usageC = usage(links.cb, false);
            for (Cls v : links.vanilla.values()) {
                Cls c = v.match;
                if (c == null) {
                    continue;
                }
                Map<Fld, Map<Fld, Double>> scores = new LinkedHashMap<>();
                for (Fld fv : v.fields.values()) {
                    if (fv.match != null) {
                        continue;
                    }
                    Set<String> uv = usageV.getOrDefault(fv, Set.of());
                    for (Fld fc : c.fields.values()) {
                        if (fc.match != null || fv.isStatic() != fc.isStatic()
                                || !links.compatible(Type.getType(fv.node.desc), Type.getType(fc.node.desc))) {
                            continue;
                        }
                        Set<String> uc = usageC.getOrDefault(fc, Set.of());
                        if (!uv.isEmpty() || !uc.isEmpty()) {
                            scores.computeIfAbsent(fv, k -> new LinkedHashMap<>()).put(fc, jaccard(uv, uc));
                        }
                    }
                }
                mutualBest(scores, FIELD_MIN, MARGIN).forEach(links::link);
            }
        }

        /** Field to "R|W vanillaMethod" for every matched method touching it. */
        private static Map<Fld, Set<String>> usage(Map<String, Cls> side, boolean isVanilla) {
            Map<Fld, Set<String>> out = new HashMap<>();
            for (Cls c : side.values()) {
                if (c.match == null) {
                    continue;
                }
                for (Mth m : c.methods.values()) {
                    if (m.match == null) {
                        continue;
                    }
                    String key = (isVanilla ? m : m.match).toString();
                    for (AbstractInsnNode insn : m.code) {
                        if (!(insn instanceof FieldInsnNode fi)) {
                            continue;
                        }
                        Fld f = Voting.resolveField(side, fi);
                        if (f == null || f.match != null) {
                            continue;
                        }
                        boolean write = fi.getOpcode() == Opcodes.PUTFIELD || fi.getOpcode() == Opcodes.PUTSTATIC;
                        out.computeIfAbsent(f, k -> new HashSet<>()).add((write ? "W " : "R ") + key);
                    }
                }
            }
            return out;
        }

        private static <T> Map<T, T> mutualBest(Map<T, Map<T, Double>> scores, double min, double margin) {
            Map<T, T> bestLeft = new HashMap<>();
            Map<T, Double> bestLeftScore = new HashMap<>();
            for (Map.Entry<T, Map<T, Double>> e : scores.entrySet()) {
                for (Map.Entry<T, Double> s : e.getValue().entrySet()) {
                    if (s.getValue() > bestLeftScore.getOrDefault(s.getKey(), -1.0)) {
                        bestLeftScore.put(s.getKey(), s.getValue());
                        bestLeft.put(s.getKey(), e.getKey());
                    }
                }
            }
            Map<T, T> result = new HashMap<>();
            for (Map.Entry<T, Map<T, Double>> e : scores.entrySet()) {
                T best = null;
                double first = -1;
                double second = -1;
                for (Map.Entry<T, Double> s : e.getValue().entrySet()) {
                    if (s.getValue() > first) {
                        second = first;
                        first = s.getValue();
                        best = s.getKey();
                    } else if (s.getValue() > second) {
                        second = s.getValue();
                    }
                }
                if (best != null && first >= min && first - Math.max(second, 0) >= margin
                        && bestLeft.get(best) == e.getKey()) {
                    result.put(e.getKey(), best);
                }
            }
            return result;
        }

        static double jaccard(Set<String> a, Set<String> b) {
            if (a.isEmpty() && b.isEmpty()) {
                return 0;
            }
            int inter = 0;
            for (String s : a) {
                if (b.contains(s)) {
                    inter++;
                }
            }
            return (double) inter / (a.size() + b.size() - inter);
        }

        /** Share of the vanilla multiset found in CheatBreaker's, which mostly only adds members. */
        static double containment(List<String> vanilla, List<String> cb) {
            if (vanilla.isEmpty()) {
                return cb.isEmpty() ? 1 : 0;
            }
            Map<String, Integer> counts = new HashMap<>();
            for (String s : cb) {
                counts.merge(s, 1, Integer::sum);
            }
            int hit = 0;
            for (String s : vanilla) {
                if (counts.merge(s, -1, Integer::sum) >= 0) {
                    hit++;
                }
            }
            double sizePenalty = (double) vanilla.size() / Math.max(vanilla.size(), cb.size());
            return (double) hit / vanilla.size() * (0.7 + 0.3 * sizePenalty);
        }
    }

