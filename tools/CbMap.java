    /** MCP's joined.srg (Notch to SRG) and stable fields.csv and methods.csv (SRG to MCP). */
    static final class Srg {
        private final Map<String, String> classes = new HashMap<>();
        private final Map<String, String> notchClasses = new HashMap<>();
        private final Map<String, String> fields = new HashMap<>();
        private final Map<String, String> methods = new HashMap<>();
        private final Map<String, String> names = new HashMap<>();

        static Srg read(Path srgZip, Path stableZip) throws IOException {
            Srg srg = new Srg();
            for (String line : lines(srgZip, "joined.srg")) {
                String[] p = line.split(" ");
                switch (p[0]) {
                    case "CL:" -> {
                        srg.classes.put(p[1], p[2]);
                        srg.notchClasses.put(p[2], p[1]);
                    }
                    case "FD:" -> srg.fields.put(p[1], p[2].substring(p[2].lastIndexOf('/') + 1));
                    case "MD:" -> srg.methods.put(p[1] + p[2], p[3].substring(p[3].lastIndexOf('/') + 1));
                    default -> {
                    }
                }
            }
            for (String csv : List.of("fields.csv", "methods.csv")) {
                for (String line : lines(stableZip, csv)) {
                    String[] p = line.split(",", 3);
                    if (p.length >= 2 && !p[0].equals("searge")) {
                        srg.names.put(p[0], p[1]);
                    }
                }
            }
            return srg;
        }

        private static List<String> lines(Path zip, String entry) throws IOException {
            try (ZipFile file = new ZipFile(zip.toFile())) {
                ZipEntry found = file.getEntry(entry);
                if (found == null) {
                    throw new IOException(zip + " has no " + entry);
                }
                return new String(file.getInputStream(found).readAllBytes(), StandardCharsets.UTF_8).lines().toList();
            }
        }

        String className(String notch) {
            return classes.getOrDefault(notch, notch);
        }

        String notchClass(String mcp) {
            return notchClasses.getOrDefault(mcp, mcp);
        }

        String fieldSrg(String owner, String name) {
            return fields.getOrDefault(owner + "/" + name, name);
        }

        String methodSrg(String owner, String name, String desc) {
            return methods.getOrDefault(owner + "/" + name + desc, name);
        }

        String mcpName(String srgName) {
            return names.getOrDefault(srgName, srgName);
        }

        String mapDesc(String desc) {
            StringBuilder out = new StringBuilder();
            for (int i = 0; i < desc.length(); ) {
                char ch = desc.charAt(i);
                if (ch != 'L') {
                    out.append(ch);
                    i++;
                    continue;
                }
                int end = desc.indexOf(';', i);
                out.append('L').append(className(desc.substring(i + 1, end))).append(';');
                i = end + 1;
            }
            return out.toString();
        }
    }
