/*
 * genmappings - turns tools/mappings.def.mjs into the C++ mapping tables.
 *
 *   node tools/genmappings.mjs
 *
 * On Lunar 1.8.9 there is nothing to translate: the def file is written in
 * the runtime's own MCP names, so this is a pass-through that lays the table
 * out in declaration order, checks ids for uniqueness and owner aliases, and
 * emits payload/src/bridge/Mappings.generated.hpp / .cpp. The old
 * Yarn->intermediary translation is gone with the Fabric resolver that
 * needed it.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { classes, methods, fields } from './mappings.def.mjs';

const HEADER_OUT = 'payload/src/bridge/Mappings.generated.hpp';
const SOURCE_OUT = 'payload/src/bridge/Mappings.generated.cpp';

const classOrder = Object.keys(classes);

function memberId(entry) {
  const suffix = entry.name === '<init>' ? 'ctor' : entry.name;
  return `${entry.owner}_${suffix}`;
}

function resolveMember(entry, kind) {
  if (!classes[entry.owner]) {
    return `owner class ${entry.owner} is not in the class table`;
  }
  return null;
}

const misses = [];
for (const entry of methods) {
  const problem = resolveMember(entry, 'method');
  if (problem) misses.push(`method ${entry.id ?? memberId(entry)}: ${problem}`);
}
for (const entry of fields) {
  const problem = resolveMember(entry, 'field');
  if (problem) misses.push(`field ${entry.id ?? memberId(entry)}: ${problem}`);
}

/* Ids first: the enum is the C++ contract. The label stays with the entry so
 * a dead id reads by its old name in logs. */
function entryId(entry) {
  return entry.id ?? memberId(entry);
}

const seenIds = new Set();
for (const entry of methods) {
  const id = entryId(entry);
  if (seenIds.has(id)) misses.push(`duplicate method id ${id}`);
  seenIds.add(id);
}
const seenFieldIds = new Set();
for (const entry of fields) {
  const id = entryId(entry);
  if (seenFieldIds.has(id)) misses.push(`duplicate field id ${id}`);
  seenFieldIds.add(id);
}

/* Enum labels must be valid C++ identifiers. */
function cppLabel(id) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(id)) {
    misses.push(`id ${id} is not a valid C++ identifier`);
  }
  return id;
}

function cppEnum(name, ids) {
  const body = ids.map((id) => `    ${cppLabel(id)},`).join('\n');
  return `enum class ${name} : std::uint16_t {\n${body}\n    Count\n};`;
}

const header = `// Generated by tools/genmappings.mjs. Do not edit.
// Lunar Client 1.8.9 / MCP stable-22 runtime names.
#pragma once

#include <cstddef>
#include <cstdint>

namespace cold::bridge {

${cppEnum('MappedClass', classOrder)}

${cppEnum('MappedMethod', methods.map(entryId))}

${cppEnum('MappedField', fields.map(entryId))}

struct ClassEntry {
    const char* readable;
    const char* runtime;
};

struct MemberEntry {
    MappedClass owner;
    const char* readable;
    const char* runtime;
    const char* descriptor;
    bool isStatic;
    bool optional;
};

inline constexpr auto kClassCount = static_cast<std::size_t>(MappedClass::Count);
inline constexpr auto kMethodCount = static_cast<std::size_t>(MappedMethod::Count);
inline constexpr auto kFieldCount = static_cast<std::size_t>(MappedField::Count);

extern const ClassEntry kClasses[kClassCount];
extern const MemberEntry kMethods[kMethodCount];
extern const MemberEntry kFields[kFieldCount];

}  // namespace cold::bridge
`;

function classRow(id) {
  return `    {"${id}", "${classes[id]}"},`;
}

function memberRow(entry) {
  const isStatic = entry.static ? 'true' : 'false';
  const optional = entry.optional ? 'true' : 'false';
  return `    {MappedClass::${entry.owner}, "${entry.id ?? memberId(entry)}", "${entry.name}", "${entry.desc}", ${isStatic}, ${optional}},`;
}

const source = `// Generated by tools/genmappings.mjs. Do not edit.
#include "Mappings.generated.hpp"

namespace cold::bridge {

const ClassEntry kClasses[kClassCount] = {
${classOrder.map(classRow).join('\n')}
};

const MemberEntry kMethods[kMethodCount] = {
${methods.map(memberRow).join('\n')}
};

const MemberEntry kFields[kFieldCount] = {
${fields.map(memberRow).join('\n')}
};

}  // namespace cold::bridge
`;

mkdirSync(dirname(HEADER_OUT), { recursive: true });
writeFileSync(HEADER_OUT, header);
writeFileSync(SOURCE_OUT, source);

console.log(
  `classes ${classOrder.length}  methods ${methods.length}  fields ${fields.length}`,
);
if (misses.length > 0) {
  console.log(`\n${misses.length} problems:`);
  for (const miss of misses) console.log(`  ${miss}`);
  process.exitCode = 1;
}
